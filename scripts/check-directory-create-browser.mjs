/* global document, requestAnimationFrame */
import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { fileURLToPath, pathToFileURL, URL } from 'node:url';
import { chromium } from 'playwright';
const require = createRequire(new URL('../packages/core/package.json', import.meta.url));
const { createServer } = await import(pathToFileURL(require.resolve('vite')).href);
const { default: solid } = await import('vite-plugin-solid');
const { default: tailwind } = await import(pathToFileURL(require.resolve('@tailwindcss/vite')).href);
const server = await createServer({ configFile: false, optimizeDeps: { entries: ['test/browser/directory-create.html'] }, root: fileURLToPath(new URL('../packages/core', import.meta.url)), plugins: [solid(), tailwind()], resolve: { dedupe: ['solid-js'] }, server: { host: '127.0.0.1', port: 0 } });
await server.listen();
let browser;
try {
  browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, hasTouch: true });
  await mkdir('/tmp/floe-directory-popup-evidence', { recursive: true });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:' + server.httpServer.address().port + '/test/browser/directory-create.html');
  for (const theme of ['light', 'dark']) for (const width of [1280, 390]) {
    await page.setViewportSize({ width, height: 900 });
    await page.evaluate(theme => document.documentElement.classList.toggle('dark', theme === 'dark'), theme);
    await page.getByRole('button', { name: 'Choose directory', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: 'Working directory' });
    const newFolder = dialog.getByRole('button', { name: 'New folder', exact: true });
    await dialog.locator('[data-filesystem-picker][aria-busy=false]').waitFor();
    await page.waitForTimeout(250);
    const pickerBefore = await dialog.boundingBox();
    await newFolder.click();
    const popup = page.getByRole('dialog', { name: 'New folder', exact: true });
    await popup.waitFor({ timeout: 2000 });
    assert.equal(await popup.getAttribute('aria-modal'), 'false');
    assert.equal(await page.locator('[aria-modal=true]').count(), 1, 'creation must not introduce a second modal');
    const pickerAfter = await dialog.boundingBox();
    assert.ok(Math.abs(pickerBefore.height - pickerAfter.height) < 1, 'popup must not grow the picker: ' + JSON.stringify({ pickerBefore, pickerAfter }));
    await page.waitForFunction(() => document.querySelector('[data-floe-popover-panel]')?.getAttribute('data-floating-presence') === 'open');
    await popup.evaluate(() => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve))));
    const bounds = await popup.boundingBox();
    assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= width, 'popup must fit the viewport: ' + JSON.stringify({ bounds, width }));
    assert.equal(await popup.evaluate(el => el.scrollWidth <= el.clientWidth), true);
    const name = popup.getByRole('textbox', { name: 'Folder name', exact: true });
    assert.equal(await name.evaluate(el => document.activeElement === el), true, 'new folder must focus the name');
    await name.fill('draft'); await page.keyboard.press('Escape');
    assert.equal(await dialog.count(), 1); assert.equal(await name.count(), 0);
    assert.equal(await newFolder.evaluate(el => document.activeElement === el), true);
    await newFolder.click(); assert.equal(await name.inputValue(), '');
    await name.fill('outside draft');
    await dialog.getByRole('textbox', { name: 'Directory path' }).click();
    await popup.waitFor({ state: 'hidden' });
    assert.equal(await dialog.count(), 1, 'outside dismissal must retain the picker');
    await newFolder.click(); assert.equal(await name.inputValue(), '');
    await popup.locator('[data-picker-create-folder]').waitFor();
    await page.waitForFunction(() => document.querySelector('[data-floe-popover-panel]')?.getAttribute('data-floating-presence') === 'open');
    assert.equal(await name.evaluate(el => document.activeElement === el), true, 'reopened popup must refocus the name');
    await popup.evaluate(el => Promise.all(el.getAnimations().map(animation => animation.finished)));
    await page.screenshot({ path: '/tmp/floe-directory-popup-evidence/' + theme + '-' + width + '.png' });
    const create = popup.getByRole('button', { name: 'Create', exact: true });
    for (const invalid of ['.', '..', 'nested/folder']) {
      await name.fill(invalid); assert.equal(await create.isDisabled(), true);
    }
    await name.fill('denied'); await page.keyboard.press('Enter');
    await page.locator('[data-picker-create-folder] [role=alert]').waitFor();
    assert.equal(await name.inputValue(), 'denied');
    assert.match(await page.locator('[data-picker-create-folder] [role=alert]').innerText(), /Write permission denied/);
    const folder = 'project-' + theme + '-' + width;
    await name.fill(folder);
    const before = await create.boundingBox();
    const cancelBefore = await popup.getByRole('button', { name: 'Cancel', exact: true }).boundingBox();
    const count = Number(await page.locator('[data-calls]').textContent());
    await page.keyboard.press('Enter');
    assert.equal(await create.getAttribute('aria-busy'), 'true');
    const during = await create.boundingBox();
    assert.ok(Math.abs(before.x - during.x) < 1 && Math.abs(before.y - during.y) < 1 && Math.abs(before.width - during.width) < 1);
    const cancelDuring = await popup.getByRole('button', { name: 'Cancel', exact: true }).boundingBox();
    assert.ok(Math.abs(cancelBefore.x - cancelDuring.x) < 1 && Math.abs(cancelBefore.y - cancelDuring.y) < 1);
    await page.keyboard.press('Enter');
    await dialog.locator('[data-picker-row-path="/home/alice/' + folder + '"]').waitFor();
    assert.equal(Number(await page.locator('[data-calls]').textContent()), count + 1);
    assert.equal(await page.locator('[data-selected]').textContent(), '');
    assert.equal(await dialog.evaluate(el => el.scrollWidth <= el.clientWidth), true);
    await newFolder.click(); await name.fill(folder); await create.click();
    await page.locator('[data-picker-create-folder] [role=alert]').waitFor(); assert.match(await page.locator('[data-picker-create-folder] [role=alert]').innerText(), /already exists/);
    await name.press('Escape');
    await newFolder.click(); await name.fill('stale-' + folder); await create.click();
    await page.getByRole('button', { name: 'Reset location', exact: true }).evaluate(button => button.click());
    await page.waitForTimeout(400);
    assert.equal(await dialog.getByRole('textbox', { name: 'Directory path' }).inputValue(), '/home/alice');
    assert.equal(await name.count(), 0);
    await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
    await dialog.waitFor({ state: 'detached' });
  }
  await page.getByRole('button', { name: 'Choose directory', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Working directory' });
  await dialog.getByRole('button', { name: 'New folder', exact: true }).click();
  await page.getByRole('dialog', { name: 'New folder', exact: true }).getByRole('textbox', { name: 'Folder name' }).fill('denied');
  await page.getByRole('dialog', { name: 'New folder', exact: true }).getByRole('button', { name: 'Create', exact: true }).click();
  await page.getByRole('button', { name: 'Close picker', exact: true }).evaluate(button => button.click());
  await dialog.waitFor({ state: 'detached' });
  await page.getByRole('button', { name: 'Choose directory', exact: true }).click();
  await page.waitForTimeout(400);
  assert.equal(await page.locator('[data-picker-create-folder] [role=alert]').count(), 0);
  await dialog.locator('[data-picker-row-path="/home/alice/project-dark-390"]').click();
  await dialog.getByRole('button', { name: 'Choose', exact: true }).click();
  assert.equal(await page.locator('[data-selected]').textContent(), '/home/alice/project-dark-390');
  assert.deepEqual(errors, []); console.log('Directory creation passed: keyboard, validation, failures, stale effects, themes and responsive geometry.');
} finally { await browser?.close(); await server.close(); }
