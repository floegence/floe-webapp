import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';
import { URL } from 'node:url';
import ts from 'typescript';

const root = new URL('../packages/core/src/components/file-browser/', import.meta.url);
const read = (name) => readFileSync(new URL(name, root), 'utf8');
const labels = JSON.parse(read('fileIconLabels.json'));
const catalog = JSON.parse(read('fileIconCatalog.json'));
const source = ts
  .transpileModule(read('fileIconDrawing.ts'), {
    compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext },
  })
  .outputText.replace(/^import .*;\n/gm, '')
  .replace(/export function /g, 'function ');
const context = vm.createContext({ labelPaths: labels });
vm.runInContext(source, context);
const labelByPath = new Map(Object.entries(labels).map(([label, value]) => [value.d, label]));
const openFolder = (body) =>
  body.replace(
    'M4 18h40a2 2 0 0 1 2 2l-2 20a4 4 0 0 1-4 4H7a4 4 0 0 1-4-4L2 20a2 2 0 0 1 2-2Z',
    'M12 18h33a2 2 0 0 1 2 3l-9 20a5 5 0 0 1-4 3H6a3 3 0 0 1-3-4l6-19a3 3 0 0 1 3-3Z'
  );
function jsx(item, compact, open = false) {
  const palette = item.palette ?? {};
  const color = palette.darkPrimary
    ? 'var(--floe-icon-monochrome)'
    : palette.primary || `var(--${item.tone})`;
  context.item = item;
  context.color = color;
  context.compact = compact;
  let body = vm.runInContext('renderFileIconBody(item, color, "file-artwork", compact)', context);
  if (open) body = openFolder(body);
  const tokens = {
    ...palette,
    'brand-background': palette.background || 'var(--raised)',
    'brand-secondary': palette.secondary || color,
    'brand-highlight': palette.highlight || color,
    'brand-shadow': palette.shadow || color,
    ...(palette.primary ? { white: '#FFFFFF' } : {}),
  };
  body = body
    .replace(/var\(--([\w-]+)\)/g, (original, key) => tokens[key] ?? original)
    .replace(/var\(--(?!floe-icon-)([\w-]+)\)/g, 'var(--floe-icon-$1)');
  // Only the closed SVG vocabulary emitted by our drawing functions is accepted.
  if (body.replace(/<\/?(?:path|rect|circle|ellipse|polygon|g)\b[^>]*>/g, '').trim())
    throw new Error('Unexpected icon markup');
  return body.replace(/([\w-]+)="([^"]*)"/g, (_, key, value) => {
    if (key === 'd' && labelByPath.has(value))
      return `d={labelPaths[${JSON.stringify(labelByPath.get(value))}].d}`;
    if (value.includes('file-artwork'))
      return key + '={`' + value.replaceAll('file-artwork', '${props.id}') + '`}';
    return `${key}=${JSON.stringify(value)}`;
  });
}
let output =
  '// Generated by scripts/generate-file-icon-artwork.mjs. Do not edit.\nimport type { Component } from "solid-js";\nimport labelPaths from "./fileIconLabels.json";\n\nexport const fileIconArtwork: Record<string, Component<{ id: string; compact: boolean }>> = {\n';
for (const item of catalog)
  for (const open of item.id === 'folder' ? [false, true] : [false]) {
    const compact = jsx(item, true, open),
      detailed = jsx(item, false, open);
    const body =
      compact === detailed ? detailed : `{props.compact ? <>${compact}</> : <>${detailed}</>}`;
    output += `${JSON.stringify(item.id + (open ? '-open' : ''))}: (${body.includes('props.') ? 'props' : ''}) => <>${body}</>,\n`;
  }
output += '};\n';
// Keep generated output stable without depending on a formatter at runtime.
if (process.argv.includes('--check')) {
  if (read('fileIconArtwork.generated.tsx') !== output)
    throw new Error(
      'Regenerate file icon artwork with node scripts/generate-file-icon-artwork.mjs'
    );
} else writeFileSync(new URL('fileIconArtwork.generated.tsx', root), output);
console.log(`Verified ${catalog.length} native SVG icon families and the open folder variant.`);
