import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, cpSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, URL } from 'node:url';
const require = createRequire(import.meta.url);
const root = dirname(require.resolve('pdfjs-dist/package.json'));
const pkg = fileURLToPath(new URL('../', import.meta.url));
const css = readFileSync(join(root, 'web/pdf_viewer.css'), 'utf8').replaceAll(':root', ':scope');
writeFileSync(join(pkg, 'dist/pdf.css'), `@scope (.floe-pdf-surface) {\n${css}\n}\n${readFileSync(join(pkg, 'src/pdf/pdf.css'), 'utf8')}`);
cpSync(join(root, 'web/images'), join(pkg, 'dist/images'), { recursive: true });
cpSync(join(root, 'LICENSE'), join(pkg, 'dist/PDFJS-LICENSE'));
